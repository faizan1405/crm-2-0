export function contextUsed(f: FollowUpFacts): string[] {
  const out = [`Name: ${f.firstName}`, `Stage: ${f.stage}`];
  if (f.company) out.push(`Business: ${f.company}`);
  out.push(f.requirement ? `Requirement: ${f.requirement}` : "Requirement: not recorded");
  out.push(f.latestInteraction ? `Latest interaction: ${f.latestInteraction.type} — ${f.latestInteraction.text.slice(0, 80)}` : "Latest interaction: none recorded");
  if (f.followUpReason) out.push(`Follow-up reason: ${f.followUpReason.slice(0, 80)}`);
  out.push(f.quotationSent ? `Quotation: ${f.quotationPackage ?? "shared"} recorded as sent` : "Quotation: none recorded as sent");
  if (f.unsuccessfulCalls) out.push(`Unanswered calls in a row: ${f.unsuccessfulCalls}`);
  if (f.objection) out.push(`Recorded objection: ${f.objection.slice(0, 80)}`);
  return out;
}

export function demoFollowUpDraft(req: FollowUpDraftRequest): FollowUpDraftResult {
  const { facts: f, purpose, tone, lang } = req;
  const v = Math.abs(req.variant) % 2;
  const notices: string[] = [];
  const r = f.requirement?.trim() || NEUTRAL_REQ[lang];
  if (!f.requirement) notices.push("No requirement is recorded, so the message uses neutral wording. Add it on the lead for a more specific draft.");
  let body: string;
  if (f.statusKey === "won" && purpose !== "confirm_followup" && purpose !== "pending_requirements") { body = AFTER_SALES[lang]; notices.push("This lead is Won, so the draft is an after-sales check-in — no new sales pitch."); }
  else if (purpose === "after_quotation" && !f.quotationSent) { body = NO_QUOTE[lang]; notices.push("No quotation is recorded as sent for this lead, so the draft doesn't claim one was."); }
  else body = BODY[lang][purpose];
  if (purpose === "unanswered_call" && f.unsuccessfulCalls === 0) notices.push("No unanswered call is recorded recently — check the wording before using it.");
  if (purpose === "confirm_followup" && !f.nextFollowUpDue) notices.push("No follow-up is booked, so no date is mentioned. Add the agreed time yourself if there is one.");
  body = body.replace("{r}", r).replace("{p}", f.quotationPackage ?? "");
  body = body.charAt(0).toUpperCase() + body.slice(1);
  if (lang !== "en") notices.push(`Demo Mode uses fixed ${LANG_LABEL[lang]} example wording; it can't freely translate or rewrite.`);
  const text = [GREET[lang][tone].replace("{n}", f.firstName), body, CLOSE[lang][tone][v]].join("\n\n");
  return { text, simulated: true, label: FU_DEMO_LABEL, contextUsed: contextUsed(f), notices };
}

/** Details a suggestion may contain: anything else that looks like a number/price/date/link is "added". */
export function allowedTokens(f: FollowUpFacts, currentDraft: string): Set<string> {
  const src = [f.firstName, f.company, f.requirement, f.quotationPackage, currentDraft].filter(Boolean).join(" ");
  return new Set(protectedTokens(src));
}
/** Blocks suggestions that introduce numbers, prices, dates or links not present in recorded facts or the current draft. */
export function draftViolations(f: FollowUpFacts, currentDraft: string, suggestion: string): string[] {
  const ok = allowedTokens(f, currentDraft);
  const src = [f.company, f.requirement, f.quotationPackage].filter(Boolean).join(" ");
  const added = protectedTokens(suggestion).filter((t) => !ok.has(t) && !src.includes(t)).map((t) => `Added “${t}”`);
  const name = suggestion.includes(f.firstName) ? [] : [`Missing name “${f.firstName}”`];
  return [...name, ...added];
}

