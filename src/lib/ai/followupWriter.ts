/** Minimised facts for one lead. Built from the permission-filtered LeadContext; no money, proofs or notes. */
export interface FollowUpFacts {
  leadId: string;
  firstName: string;
  company?: string;
  requirement?: string;
  stage: string;
  statusKey: LeadContext["facts"]["statusKey"];
  latestInteraction?: { type: string; text: string; at: string };
  followUpReason?: string;
  /** Only true when the CRM records a quotation share (or a WhatsApp quotation log) for this lead. */
  quotationSent: boolean;
  quotationPackage?: string;
  unsuccessfulCalls: number;
  objection?: string;
  /** Next pending follow-up due time (ISO), if any. */
  nextFollowUpDue?: string;
}

export interface FollowUpDraftRequest { facts: FollowUpFacts; purpose: FollowUpPurpose; tone: RewriteTone; lang: Exclude<RewriteLang, "keep">; variant: number }
export interface FollowUpDraftResult { text: string; simulated: true; label: string; contextUsed: string[]; notices: string[] }
export interface FollowUpDraftProvider { draft(req: FollowUpDraftRequest): Promise<FollowUpDraftResult> }

export interface QuoteShareLite { leadId: string; packageNameSnapshot: string; userConfirmedSent?: boolean }

export function buildFollowUpFacts(ctx: LeadContext, shares: QuoteShareLite[], followUpNote?: string): FollowUpFacts {
  const own = shares.filter((s) => s.leadId === ctx.leadId && s.userConfirmedSent !== false);
  const f = ctx.facts;
  return {
    leadId: ctx.leadId, firstName: ctx.name.trim().split(/\s+/)[0] ?? ctx.name, stage: ctx.stage, statusKey: f.statusKey,
    quotationSent: own.length > 0, unsuccessfulCalls: f.unsuccessfulStreak,
    ...(own[0] ? { quotationPackage: own[0].packageNameSnapshot } : {}),
    ...(ctx.company ? { company: ctx.company } : {}),
    ...(ctx.requirement ? { requirement: ctx.requirement } : {}),
    ...(f.lastInteraction ? { latestInteraction: f.lastInteraction } : {}),
    ...(followUpNote?.trim() ? { followUpReason: followUpNote.trim() } : {}),
    ...(f.lostReason ? { objection: f.lostReason } : {}),
    ...(f.nextFollowUpDue ? { nextFollowUpDue: f.nextFollowUpDue } : {}),
  };
}

/** Suggest a purpose from recorded facts only. */
export function suggestPurpose(f: FollowUpFacts): FollowUpPurpose {
  if (f.statusKey === "won") return f.nextFollowUpDue ? "confirm_followup" : "reconnect";
  if (f.unsuccessfulCalls > 0) return "unanswered_call";
  if (f.quotationSent && f.statusKey === "proposal") return "after_quotation";
  if (f.followUpReason && f.nextFollowUpDue) return "confirm_followup";
  if (f.statusKey === "new" && !f.latestInteraction) return "first_enquiry";
  if (!f.requirement) return "pending_requirements";
  return "no_response";
}

